#!/usr/bin/env node
/**
 * Build an upsert SQL file for public.teaching_ideas from the private catalog CSV.
 *
 *   node scripts/seed-teaching-ideas.mjs <path/to/sidekick_ingest.csv> <out.sql>
 *
 * It only writes a local .sql file; it never connects to a database. Run the
 * output in the Supabase SQL editor yourself. Keep the CSV and the .sql out of git.
 *
 * Drops the two rows about the Sidekick app itself and ignores has_free_asset
 * (not verified file by file, so the site never shows it).
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

/**
 * The two rows to drop (the app's own iOS/Android announcements), stored as
 * SHA-256 of their catalog id so private catalog ids never land in this repo.
 */
export const DROPPED_ID_HASHES = [
	'4a9ad4793262370a356fde71309e47e73a208360370e6f05a783eee9c7063979',
	'73feb33a10574ff0c5ec4ada0c3345246d6b6b6d69cbc930610fd1e97f30b2df'
];

/** @param {string} id */
export const isDropped = (id) =>
	DROPPED_ID_HASHES.includes(createHash('sha256').update(id).digest('hex'));
const COURSES = new Set(['general', 'OT', 'NT', 'BoM', 'D&C']);

/** Minimal RFC 4180 CSV parser (quoted fields, doubled quotes, newlines in quotes). */
/** @param {string} text @returns {Record<string, string>[]} */
export function parseCsv(text) {
	const rows = [];
	let row = [];
	let field = '';
	let quoted = false;
	for (let i = 0; i < text.length; i++) {
		const c = text[i];
		if (quoted) {
			if (c === '"' && text[i + 1] === '"') {
				field += '"';
				i++;
			} else if (c === '"') quoted = false;
			else field += c;
		} else if (c === '"') quoted = true;
		else if (c === ',') {
			row.push(field);
			field = '';
		} else if (c === '\n' || c === '\r') {
			if (c === '\r' && text[i + 1] === '\n') i++;
			row.push(field);
			rows.push(row);
			row = [];
			field = '';
		} else field += c;
	}
	if (field || row.length) {
		row.push(field);
		rows.push(row);
	}
	const [header, ...body] = rows.filter((r) => r.some((v) => v !== ''));
	return body.map((r) => Object.fromEntries(header.map((h, i) => [h, r[i] ?? ''])));
}

/** @param {unknown} s */
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

/** @param {Record<string, string>[]} records */
export function buildSql(records) {
	const kept = records.filter((r) => !isDropped(r.id));
	const gone = records.filter((r) => isDropped(r.id)).map((r) => r.source_ref || r.id);
	for (const r of kept) {
		if (!COURSES.has(r.course)) throw new Error(`Unknown course "${r.course}" on ${r.id}`);
		for (const k of ['book', 'category', 'title', 'summary'])
			if (!r[k]) throw new Error(`Empty ${k} on ${r.id}`);
	}
	const values = kept.map(
		(r) =>
			`(${[r.source_ref || r.id, r.course, r.book, r.category, r.title, r.summary].map(q).join(', ')})`
	);
	const sql = `-- Generated by scripts/seed-teaching-ideas.mjs. PRIVATE: do not commit.
begin;
insert into public.teaching_ideas (source_ref, course, book, category, title, summary) values
${values.join(',\n')}
on conflict (source_ref) do update set
	course = excluded.course, book = excluded.book, category = excluded.category,
	title = excluded.title, summary = excluded.summary, updated_at = now();
${gone.length ? `delete from public.teaching_ideas where source_ref in (${gone.map(q).join(', ')});` : ''}
commit;
`;
	return { sql, kept: kept.length, dropped: records.length - kept.length };
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const [csvPath, outPath] = process.argv.slice(2);
	if (!csvPath || !outPath) {
		console.error('usage: node scripts/seed-teaching-ideas.mjs <ingest.csv> <out.sql>');
		process.exit(1);
	}
	const { sql, kept, dropped } = buildSql(parseCsv(readFileSync(csvPath, 'utf8')));
	writeFileSync(outPath, sql);
	console.log(`wrote ${outPath}: ${kept} rows to upsert, ${dropped} dropped`);
}
