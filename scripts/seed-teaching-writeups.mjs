#!/usr/bin/env node
/**
 * Build an UPDATE SQL file that adds full write-ups to existing teaching ideas.
 *
 *   node scripts/seed-teaching-writeups.mjs <writeups.json> <out.sql>
 *
 * writeups.json is a private array of
 *   { source_ref, slug, title, summary, body, image_url?, image_alt? }
 * written in our own words. It never enters git. This script only writes a
 * local .sql file and never connects to a database; review it, then run it in
 * the Supabase SQL editor for the project you mean (never prod without Patrick).
 *
 * It refuses content that breaks the public rules: links, Facebook mentions,
 * our own product names, an image without alt text, or a bad slug.
 */

import { readFileSync, writeFileSync } from 'node:fs';

const SLUG = /^[a-z0-9]+(-[a-z0-9]+)*$/;
/** @type {Array<[RegExp, string]>} */
const BANNED = [
	[/https?:\/\/|www\./i, 'links'],
	[/facebook|\bfb\b/i, 'Facebook mentions'],
	[/sidekick|narrow road/i, 'our product names']
];

/** @param {string | null | undefined} v */
const lit = (v) => (v == null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

/** @param {Array<Record<string, string | null | undefined>>} writeups */
export function buildWriteupSql(writeups) {
	const slugs = new Set();
	const lines = [
		'-- Generated by scripts/seed-teaching-writeups.mjs. Review before running.',
		'begin;'
	];
	for (const w of writeups) {
		const where = w.slug ?? w.source_ref ?? '?';
		if (!w.source_ref) throw new Error(`${where}: missing source_ref`);
		if (!w.slug || !SLUG.test(w.slug)) throw new Error(`${where}: bad slug`);
		if (slugs.has(w.slug)) throw new Error(`${where}: duplicate slug`);
		slugs.add(w.slug);
		for (const f of ['title', 'summary', 'body'])
			if (!w[f]?.trim()) throw new Error(`${where}: missing ${f}`);
		if (w.image_url && !w.image_alt?.trim()) throw new Error(`${where}: image needs alt text`);
		const text = [w.title, w.summary, w.body, w.image_alt].join('\n');
		for (const [re, what] of BANNED)
			if (re.test(text)) throw new Error(`${where}: contains ${what}`);
		lines.push(
			`update public.teaching_ideas set slug = ${lit(w.slug)}, title = ${lit(w.title)}, ` +
				`summary = ${lit(w.summary)}, body_md = ${lit(w.body)}, image_url = ${lit(w.image_url)}, ` +
				`image_alt = ${lit(w.image_url ? w.image_alt : null)}, updated_at = now() ` +
				`where source_ref = ${lit(w.source_ref)};`
		);
	}
	lines.push('commit;', '');
	return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const [input, out] = process.argv.slice(2);
	if (!input || !out) {
		console.error('usage: seed-teaching-writeups.mjs <writeups.json> <out.sql>');
		process.exit(1);
	}
	const writeups = JSON.parse(readFileSync(input, 'utf8'));
	writeFileSync(out, buildWriteupSql(writeups));
	console.log(`wrote ${writeups.length} updates to ${out}`);
}
